  function convert(cat, from, to, v) {
    if (cat.special && cat.name === 'Temperatura') {
      let k;
      switch (from.symbol) {
        case '°C': k = v + 273.15; break;
        case 'K':  k = v; break;
        case '°F': k = (v - 32) * 5/9 + 273.15; break;
        default:   k = v;
      }
      switch (to.symbol) {
        case '°C': return k - 273.15;
        case 'K':  return k;
        case '°F': return (k - 273.15) * 9/5 + 32;
        default:   return k;
      }
    }
    return v * from.toBase / to.toBase;
  }

  // ====================== Section properties (parametric) ======================
  const sqrt3 = Math.sqrt(3);
  function rectangle(b, h) {
    const A = b * h;
    return {
      A,
      Ix: b * h * h * h / 12,
      Iy: h * b * b * b / 12,
      Wx: b * h * h / 6,
      Wy: h * b * b / 6,
      ix: h / (2 * sqrt3),
      iy: b / (2 * sqrt3),
      perimeter: 2 * (b + h),
    };
  }
  function hollowRect(b, h, t) {
    if (2 * t >= Math.min(b, h)) throw new Error('Spessore troppo grande');
    const bi = b - 2*t, hi = h - 2*t;
    const A = b*h - bi*hi;
    const Ix = (b*h*h*h - bi*hi*hi*hi) / 12;
    const Iy = (h*b*b*b - hi*bi*bi*bi) / 12;
    return {
      A, Ix, Iy,
      Wx: Ix / (h/2), Wy: Iy / (b/2),
      ix: Math.sqrt(Ix/A), iy: Math.sqrt(Iy/A),
      perimeter: 2*(b+h) + 2*(bi+hi),
    };
  }
  function solidCircle(D) {
    const A = Math.PI*D*D/4;
    const I = Math.PI*Math.pow(D,4)/64;
    const W = Math.PI*D*D*D/32;
    return { A, Ix:I, Iy:I, Wx:W, Wy:W, ix:D/4, iy:D/4, perimeter: Math.PI*D };
  }
  function tube(De, t) {
    const Di = De - 2*t;
    if (Di < 0) throw new Error('Spessore troppo grande');
    const A = Math.PI*(De*De - Di*Di)/4;
    const I = Math.PI*(Math.pow(De,4) - Math.pow(Di,4))/64;
    const W = I/(De/2);
    return { A, Ix:I, Iy:I, Wx:W, Wy:W, ix:Math.sqrt(I/A), iy:Math.sqrt(I/A), perimeter: Math.PI*(De+Di) };
  }

